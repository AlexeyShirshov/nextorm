using System.ComponentModel.DataAnnotations;
using System.ComponentModel.DataAnnotations.Schema;
using NextORM.Core;

namespace NextORM.AotScenarios;

/// <summary>
/// The capability shapes that write or stream (#370 Stream B): the DML builders, bulk insert, raw-SQL row
/// mapping and the asynchronous row stream. Each one is idempotent — it scopes its rows with a fixed
/// marker and removes them before and after the read — so the native arm and its JIT control can run
/// against the same database without seeing each other's leftovers.
/// </summary>
public static partial class AotScenarioCatalog
{
    private static object? RowStreaming(IDataContext context)
    {
        // The terminal streams the reader instead of buffering the result set; the shape is proven only if
        // the whole sequence arrives in order from the published native binary.
        var ids = new List<int>();
        var rows = context.From<AotSimpleEntity>()
            .OrderBy(entity => entity.Id)
            .ToAsyncEnumerable()
            .GetAsyncEnumerator();
        try
        {
            while (rows.MoveNextAsync().AsTask().GetAwaiter().GetResult())
                ids.Add(rows.Current.Id);
        }
        finally
        {
            rows.DisposeAsync().AsTask().GetAwaiter().GetResult();
        }

        return string.Join(",", ids);
    }

    private static object? RawRowMapping(IDataContext context)
    {
        // Both raw mapping forms: a scalar set and a mapped entity bound by column name.
        string scalars;
        using (var result = context.ExecuteRaw("select id from person order by id"))
            scalars = string.Join(",", result.Read<int>());

        string mapped;
        using (var result = context.ExecuteRaw("select id, name from person order by id"))
            mapped = string.Join(";", result.Read<AotPerson>()
                .Select(person => $"{person.Id}:{person.Name ?? "null"}"));

        return $"scalars={scalars};mapped={mapped}";
    }

    private static object? DmlBuilders(IDataContext context)
    {
        // insert (returning the generated key) -> update -> read -> delete. The generated key is never
        // printed: the native arm and the control run one after the other and would see different values.
        var cleaned = context.CreateDeleteBuilder<AotWriteEntity>()
            .Where(entity => entity.Name == WriteMarker)
            .Delete();
        var id = context.CreateInsertBuilder<AotWriteEntity>()
            .Value(entity => entity.Name, WriteMarker)
            .Value(entity => entity.Age, 7)
            .ReturningIdentity(entity => entity.Id)
            .Single();
        var updated = context.CreateUpdateBuilder<AotWriteEntity>()
            .Set(entity => entity.Age, 8)
            .Where(entity => entity.Id == id)
            .Update();
        var ages = context.From<AotWriteEntity>()
            .Where(entity => entity.Name == WriteMarker)
            .Select(entity => entity.Age)
            .ToList();
        var removed = context.CreateDeleteBuilder<AotWriteEntity>()
            .Where(entity => entity.Name == WriteMarker)
            .Delete();

        return $"cleaned={cleaned};updated={updated};ages={string.Join(",", ages)};removed={removed}";
    }

    private static object? BulkInsert(IDataContext context)
    {
        // The provider's bulk path (a chunked parameterised insert where no native API exists) writes a
        // whole sequence in one command; the rows are read back ordered by value, then removed.
        var cleaned = context.CreateDeleteBuilder<AotWriteEntity>()
            .Where(entity => entity.Name == BulkMarker)
            .Delete();
        var written = context.CreateBulkInsertBuilder<AotWriteEntity>()
            .Values(Enumerable.Range(0, 5).Select(age => new AotWriteEntity { Name = BulkMarker, Age = age }))
            .BulkInsert();
        var ages = context.From<AotWriteEntity>()
            .Where(entity => entity.Name == BulkMarker)
            .OrderBy(entity => entity.Age)
            .Select(entity => entity.Age)
            .ToList();
        var removed = context.CreateDeleteBuilder<AotWriteEntity>()
            .Where(entity => entity.Name == BulkMarker)
            .Delete();

        return $"cleaned={cleaned};written={written};ages={string.Join(",", ages)};removed={removed}";
    }

    private const string WriteMarker = "aot-dml";
    private const string BulkMarker = "aot-bulk";
}

/// <summary>
/// The write fixture: the key is generated by the table, so no shape has to know or print it.
/// </summary>
[SqlTable("insert_entity")]
public sealed class AotWriteEntity
{
    [Key]
    [DatabaseGenerated(DatabaseGeneratedOption.Identity)]
    [Column("id")]
    public long Id { get; set; }

    [Column("name")]
    public string? Name { get; set; }

    [Column("age")]
    public int Age { get; set; }
}
