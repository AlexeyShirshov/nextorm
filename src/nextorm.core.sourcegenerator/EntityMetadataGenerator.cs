using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace NextORM.Core.SourceGenerator;

/// <summary>
/// Emits a compile-time description of every entity mapping this project declares, so the runtime can
/// build the mapping without reflecting over the entity's members.
/// <para>
/// The description is the same data the reflective auto-build derives from attributes: the table name,
/// the mapped columns, keys and identity/computed flags. The generator is deliberately conservative —
/// a type that uses a construct it does not reproduce exactly (a relationship, a query filter, a value or
/// JSON converter, a range pair, a duration or decimal-precision mapping, inheritance, a generic or
/// nested-in-generic declaration) is simply not covered, and the runtime keeps the reflective path for
/// it. Coverage therefore grows by widening this description, never by guessing.
/// </para>
/// <para>
/// Run-time mappings are unaffected: a fluent <c>From&lt;T&gt;(cfg =&gt; ...)</c> mapping, an EF Core
/// model or a per-scope variant is published into the metadata cache first, and the generated
/// description is only consulted when no such entry exists.
/// </para>
/// </summary>
[Generator]
internal sealed class EntityMetadataGenerator : IIncrementalGenerator
{
    private const string GeneratedNamespace = "NextORM.Core.Generated";
    private const string ProviderName = "__NextOrmEntityMetadata";
    private const string CoreNamespace = "NextORM.Core";

    private const string SqlTableAttribute = CoreNamespace + ".SqlTableAttribute";
    private const string TableAttribute = "System.ComponentModel.DataAnnotations.Schema.TableAttribute";
    private const string ColumnAttribute = "System.ComponentModel.DataAnnotations.Schema.ColumnAttribute";
    private const string KeyAttribute = "System.ComponentModel.DataAnnotations.KeyAttribute";
    private const string DatabaseGeneratedAttribute = "System.ComponentModel.DataAnnotations.Schema.DatabaseGeneratedAttribute";
    private const string NotMappedAttribute = "System.ComponentModel.DataAnnotations.Schema.NotMappedAttribute";
    private const string TimestampAttribute = "System.ComponentModel.DataAnnotations.TimestampAttribute";
    private const string DecimalPrecisionAttribute = CoreNamespace + ".DecimalPrecisionAttribute";
    private const string CollationAttribute = CoreNamespace + ".CollationAttribute";
    private const string DurationAttribute = CoreNamespace + ".DurationAttribute";
    private const string RangeColumnsAttribute = CoreNamespace + ".RangeColumnsAttribute";
    private const string QueryFilterAttribute = CoreNamespace + ".QueryFilterAttribute";

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var declared = context.SyntaxProvider.CreateSyntaxProvider(
                static (node, _) => node is TypeDeclarationSyntax,
                static (ctx, _) => ctx.SemanticModel.GetDeclaredSymbol((TypeDeclarationSyntax)ctx.Node) as INamedTypeSymbol)
            .Where(static symbol => symbol is not null)
            .Select(static (symbol, _) => symbol!);

        context.RegisterSourceOutput(declared.Collect(), static (output, symbols) => Emit(output, symbols));
    }

    private static void Emit(SourceProductionContext context, ImmutableArray<INamedTypeSymbol> symbols)
    {
        var seen = new HashSet<INamedTypeSymbol>(SymbolEqualityComparer.Default);
        var covered = new List<CoveredEntity>();
        foreach (var symbol in symbols)
        {
            if (!seen.Add(symbol) || Describe(symbol) is not { } entity)
                continue;
            covered.Add(entity);
        }

        if (covered.Count == 0)
            return;

        covered.Sort(static (left, right) => string.CompareOrdinal(left.FullName, right.FullName));

        var source = new StringBuilder();
        source.AppendLine("// <auto-generated/>");
        source.AppendLine("#nullable enable");
        source.AppendLine();
        source.Append("namespace ").Append(GeneratedNamespace).AppendLine(";");
        source.AppendLine();
        source.Append("internal static class ").AppendLine(ProviderName);
        source.AppendLine("{");

        // One annotated type handle per entity: the annotation is what lets the generated code resolve a
        // property by name without a trim warning, and it also tells the trimmer to keep the members.
        for (var i = 0; i < covered.Count; i++)
        {
            source.Append("    [global::System.Diagnostics.CodeAnalysis.DynamicallyAccessedMembers(global::System.Diagnostics.CodeAnalysis.DynamicallyAccessedMemberTypes.PublicProperties)]")
                .AppendLine();
            source.Append("    private static readonly global::System.Type Entity").Append(i)
                .Append(" = typeof(global::").Append(covered[i].FullName).AppendLine(");");
            source.AppendLine();
        }

        source.AppendLine("    [global::System.Runtime.CompilerServices.ModuleInitializer]");
        source.AppendLine("    internal static void Initialize()");
        source.AppendLine("    {");

        for (var i = 0; i < covered.Count; i++)
            EmitEntity(source, covered[i], i);

        source.AppendLine("    }");
        source.AppendLine("}");
        context.AddSource("__NextOrmEntityMetadata.g.cs", source.ToString());
    }

    private static void EmitEntity(StringBuilder source, CoveredEntity entity, int index)
    {
        source.Append("        global::NextORM.Core.GeneratedEntityMetadata.Register(typeof(global::")
            .Append(entity.FullName).Append("), static () =>").AppendLine();
        source.AppendLine("            new global::NextORM.Core.EntityMetadataDescriptor");
        source.AppendLine("            {");
        source.Append("                TableName = ").Append(Literal(entity.TableName)).AppendLine(",");
        if (entity.Schema is null)
            source.AppendLine("                Schema = null,");
        else
            source.Append("                Schema = ").Append(Literal(entity.Schema)).AppendLine(",");
        source.Append("                IsTableNameAuto = ").Append(Boolean(entity.IsTableNameAuto)).AppendLine(",");
        source.Append("                TypeName = ").Append(Literal(entity.TypeName)).AppendLine(",");
        source.AppendLine("                Properties = new global::NextORM.Core.EntityPropertyDescriptor[]");
        source.AppendLine("                {");
        foreach (var property in entity.Properties)
        {
            source.AppendLine("                    new global::NextORM.Core.EntityPropertyDescriptor");
            source.AppendLine("                    {");
            source.Append("                        Property = Entity").Append(index)
                .Append(".GetProperty(").Append(Literal(property.Name)).AppendLine(")!,");
            source.Append("                        ColumnName = ").Append(Literal(property.ColumnName)).AppendLine(",");
            source.Append("                        IsColumnNameAuto = ").Append(Boolean(property.IsColumnNameAuto)).AppendLine(",");
            if (property.IsKey)
                source.AppendLine("                        IsKey = true,");
            if (property.IsIdentity)
                source.AppendLine("                        IsIdentity = true,");
            if (property.IsComputed)
                source.AppendLine("                        IsComputed = true,");
            if (property.DecimalPrecision is { } precision)
                source.Append("                        DecimalPrecision = ").Append(precision).AppendLine(",");
            if (property.DecimalScale is { } scale)
                source.Append("                        DecimalScale = ").Append(scale).AppendLine(",");
            if (property.Collation is not null)
                source.Append("                        Collation = ").Append(Literal(property.Collation)).AppendLine(",");
            if (property.DurationUnit is { } durationUnit)
                source.Append("                        DurationUnit = (global::NextORM.Core.DurationUnit)").Append(durationUnit).AppendLine(",");
            if (property.DurationPrecision != 0)
                source.Append("                        DurationPrecision = ").Append(property.DurationPrecision).AppendLine(",");
            if (property.Range is { } range)
            {
                source.Append("                        RangeColumns = new global::NextORM.Core.RangeColumnsMetadata(")
                    .Append(Literal(range.LowerColumn)).Append(", ")
                    .Append(Literal(range.UpperColumn)).Append(", ")
                    .Append(Boolean(range.LowerInclusive)).Append(", ")
                    .Append(Boolean(range.UpperInclusive)).AppendLine("),");
            }

            source.AppendLine("                    },");
        }

        source.AppendLine("                },");

        if (entity.Filters.Count > 0)
        {
            source.AppendLine("                Filters = new global::NextORM.Core.EntityFilterDescriptor[]");
            source.AppendLine("                {");
            foreach (var filter in entity.Filters)
            {
                source.AppendLine("                    new global::NextORM.Core.EntityFilterDescriptor");
                source.AppendLine("                    {");
                if (filter.Key is not null)
                    source.Append("                        Key = ").Append(Literal(filter.Key)).AppendLine(",");
                if (filter.MemberReference is not null)
                {
                    source.Append("                        ").Append(filter.IsLambda ? "Lambda" : "Func")
                        .Append(" = ").Append(filter.MemberReference).AppendLine(",");
                }

                source.AppendLine("                    },");
            }

            source.AppendLine("                },");
        }

        source.AppendLine("            }.Build());");
    }

    private static string Boolean(bool value) => value ? "true" : "false";

    /// <summary>Writes a C# string literal, escaping what a table or column name may contain.</summary>
    private static string Literal(string value)
    {
        var builder = new StringBuilder(value.Length + 2);
        builder.Append('"');
        foreach (var character in value)
        {
            switch (character)
            {
                case '"': builder.Append("\\\""); break;
                case '\\': builder.Append("\\\\"); break;
                case '\n': builder.Append("\\n"); break;
                case '\r': builder.Append("\\r"); break;
                case '\t': builder.Append("\\t"); break;
                default: builder.Append(character); break;
            }
        }

        builder.Append('"');
        return builder.ToString();
    }

    private static CoveredEntity? Describe(INamedTypeSymbol symbol)
    {
        if (symbol.TypeKind is not (TypeKind.Class or TypeKind.Interface))
            return null;
        // An interface is abstract by definition; only an abstract class is skipped.
        if (symbol.TypeKind == TypeKind.Class && symbol.IsAbstract)
            return null;
        if (symbol.IsStatic || symbol.IsGenericType)
            return null;
        if (!IsAccessibleInsideAssembly(symbol))
            return null;

        // Inheritance changes which properties are visible (FlattenHierarchy) and lets an attribute on a
        // base interface win, so the reflective result is not reproducible from this declaration alone.
        if (symbol.TypeKind == TypeKind.Class && symbol.BaseType is { SpecialType: not SpecialType.System_Object })
            return null;
        if (symbol.TypeKind == TypeKind.Interface && symbol.Interfaces.Length != 0)
            return null;

        var typeAttributes = symbol.GetAttributes();
        string? tableName = null;
        var tableNameAuto = true;
        var hasMappingAttribute = false;
        var filters = new List<CoveredFilter>();

        foreach (var attribute in typeAttributes)
        {
            var name = attribute.AttributeClass?.ToDisplayString() ?? string.Empty;
            if (name == SqlTableAttribute)
            {
                if (attribute.ConstructorArguments.Length != 1 || attribute.ConstructorArguments[0].Value is not string declared)
                    return null;
                tableName = declared;
                tableNameAuto = false;
                hasMappingAttribute = true;
            }
            else if (name == TableAttribute)
            {
                tableName = attribute.ConstructorArguments.Length == 1 && attribute.ConstructorArguments[0].Value is string declared
                    ? declared
                    : NamedString(attribute, "Name");
                if (tableName is null)
                    return null;
                tableNameAuto = false;
                hasMappingAttribute = true;
            }
            else if (name == QueryFilterAttribute)
            {
                if (DescribeFilter(symbol, attribute) is not { } filter)
                    return null;
                filters.Add(filter);
            }
            else if (IsUnreproducible(name))
            {
                return null;
            }
        }

        var properties = new List<CoveredProperty>();
        foreach (var member in symbol.GetMembers())
        {
            if (member is not IPropertySymbol property)
                continue;
            if (property.IsStatic || property.IsIndexer)
                continue;
            if (property.DeclaredAccessibility != Accessibility.Public)
                continue;
            // GetProperties(Public | Instance) returns only writable properties; a get-only or init-only
            // property is not a column. An init-only setter counts as writable for reflection.
            if (property.SetMethod is null)
                continue;

            string? columnName = null;
            string? declaredColumn = null;
            var isKey = false;
            var isIdentity = false;
            var isComputed = false;
            int? decimalPrecision = null;
            int? decimalScale = null;
            string? collation = null;
            int? durationUnit = null;
            var durationPrecision = 0;
            RangeDescriptor? range = null;

            foreach (var attribute in property.GetAttributes())
            {
                var name = attribute.AttributeClass?.ToDisplayString() ?? string.Empty;
                if (name == ColumnAttribute)
                {
                    declaredColumn = attribute.ConstructorArguments.Length == 1
                        ? attribute.ConstructorArguments[0].Value as string
                        : NamedString(attribute, "Name");
                }
                else if (name == KeyAttribute)
                {
                    isKey = true;
                }
                else if (name == DatabaseGeneratedAttribute)
                {
                    // DatabaseGeneratedOption: None = 0, Identity = 1, Computed = 2.
                    var option = attribute.ConstructorArguments.Length == 1 && attribute.ConstructorArguments[0].Value is int value
                        ? value
                        : 0;
                    isIdentity = option == 1;
                    isComputed = option == 2;
                }
                else if (name == DecimalPrecisionAttribute)
                {
                    decimalPrecision = IntArgument(attribute, 0, "Precision");
                    decimalScale = IntArgument(attribute, 1, "Scale");
                }
                else if (name == CollationAttribute)
                {
                    collation = StringArgument(attribute, 0, "Name");
                    if (string.IsNullOrEmpty(collation))
                        return null;
                }
                else if (name == DurationAttribute)
                {
                    // The parameterless constructor means ticks, the CLR storage unit.
                    durationUnit = IntArgument(attribute, 0, "Unit") ?? 0;
                    durationPrecision = IntArgument(attribute, 1, "Precision") ?? 0;
                }
                else if (name == RangeColumnsAttribute)
                {
                    var lower = StringArgument(attribute, 0, "LowerColumn");
                    var upper = StringArgument(attribute, 1, "UpperColumn");
                    if (string.IsNullOrEmpty(lower) || string.IsNullOrEmpty(upper))
                        return null;
                    range = new RangeDescriptor(
                        lower!,
                        upper!,
                        BoolArgument(attribute, "LowerInclusive") ?? true,
                        BoolArgument(attribute, "UpperInclusive") ?? false);
                }
                else if (name is NotMappedAttribute or TimestampAttribute || IsUnreproducible(name))
                {
                    return null;
                }
            }

            // A range pair declares its own column names and is refused together with [Column] by the
            // reflective build; the combination is not reproduced here, the type keeps that path.
            if (range is not null)
            {
                if (declaredColumn is not null || !IsRangeType(property.Type))
                    return null;
                columnName = range.LowerColumn;
            }
            else if (!string.IsNullOrEmpty(declaredColumn))
            {
                columnName = declaredColumn;
            }

            if (columnName is not null || isKey)
                hasMappingAttribute = true;

            properties.Add(new CoveredProperty(
                Name: property.Name,
                ColumnName: columnName ?? property.Name,
                IsColumnNameAuto: columnName is null,
                IsKey: isKey,
                IsIdentity: isIdentity,
                IsComputed: isComputed,
                DecimalPrecision: decimalPrecision,
                DecimalScale: decimalScale,
                Collation: collation,
                DurationUnit: durationUnit,
                DurationPrecision: durationPrecision,
                Range: range));
        }

        // A type with no mapping attribute at all is not necessarily an entity (the auto table name makes
        // every settable class an entity, which would describe plain DTOs and value objects), so it keeps
        // the reflective path until it declares its mapping.
        if (!hasMappingAttribute || properties.Count == 0)
            return null;

        var fullName = symbol.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat).Replace("global::", string.Empty);
        return new CoveredEntity(fullName, tableName ?? symbol.Name, tableNameAuto, Schema: null, symbol.Name, properties, filters);
    }

    /// <summary>
    /// Whether an attribute makes the mapping unreproducible. Every <c>NextORM.Core</c> mapping attribute
    /// other than <see cref="SqlTableAttribute"/> is excluded: relationships, query filters, value and JSON
    /// converters, range pairs, durations, collations, decimal precision, dynamic-columns stores and shard
    /// keys all change the resulting metadata in ways this generator does not model yet.
    /// </summary>
    private static bool IsUnreproducible(string attributeFullName)
    {
        if (attributeFullName is SqlTableAttribute or DecimalPrecisionAttribute or CollationAttribute
            or DurationAttribute or RangeColumnsAttribute or QueryFilterAttribute)
            return false;

        var namespaceEnd = attributeFullName.LastIndexOf('.');
        return namespaceEnd > 0 && attributeFullName.Substring(0, namespaceEnd) == CoreNamespace;
    }

    /// <summary>
    /// Reads one <c>[QueryFilter]</c> declaration, or returns <see langword="null"/> when it cannot be
    /// reproduced: both forms declared (the reflective build throws), a member that is not accessible to
    /// generated code, or a member whose type is not a predicate/function.
    /// </summary>
    private static CoveredFilter? DescribeFilter(INamedTypeSymbol entity, AttributeData attribute)
    {
        var key = NamedString(attribute, "FilterKey");
        var lambdaName = NamedString(attribute, "FilterLambda");
        var funcName = NamedString(attribute, "FilterFunc");

        var hasLambda = !string.IsNullOrWhiteSpace(lambdaName);
        var hasFunc = !string.IsNullOrWhiteSpace(funcName);
        if (hasLambda && hasFunc)
            return null;

        if (!hasLambda && !hasFunc)
            return string.IsNullOrWhiteSpace(key) ? null : new CoveredFilter(key, MemberReference: null, IsLambda: false);

        var member = ResolveStaticMember(entity, hasLambda ? lambdaName! : funcName!, expectLambda: hasLambda);
        return member is null ? null : new CoveredFilter(key, member, hasLambda);
    }

    /// <summary>
    /// Names a static field, property or parameterless method of the entity so generated code reads it
    /// directly, replacing the reflective <c>GetMember</c> + <c>GetValue</c>/<c>Invoke</c> lookup.
    /// </summary>
    private static string? ResolveStaticMember(INamedTypeSymbol entity, string name, bool expectLambda)
    {
        var typeReference = "global::" + entity.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat).Replace("global::", string.Empty);

        foreach (var member in entity.GetMembers(name))
        {
            switch (member)
            {
                case IPropertySymbol property when property.IsStatic && IsAccessibleToGeneratedCode(property.DeclaredAccessibility):
                    return DerivesFrom(property.Type, expectLambda ? "System.Linq.Expressions.LambdaExpression" : "System.Delegate")
                        ? typeReference + "." + property.Name
                        : null;
                case IFieldSymbol field when field.IsStatic && IsAccessibleToGeneratedCode(field.DeclaredAccessibility):
                    return DerivesFrom(field.Type, expectLambda ? "System.Linq.Expressions.LambdaExpression" : "System.Delegate")
                        ? typeReference + "." + field.Name
                        : null;
                case IMethodSymbol method when method.IsStatic && method.Parameters.Length == 0 && !method.IsGenericMethod
                    && IsAccessibleToGeneratedCode(method.DeclaredAccessibility):
                    return DerivesFrom(method.ReturnType, expectLambda ? "System.Linq.Expressions.LambdaExpression" : "System.Delegate")
                        ? typeReference + "." + method.Name + "()"
                        : null;
            }
        }

        return null;
    }

    // A private member is not reachable from the generated class, so the type keeps the reflective path.
    private static bool IsAccessibleToGeneratedCode(Accessibility accessibility)
        => accessibility is Accessibility.Public or Accessibility.Internal or Accessibility.ProtectedOrInternal;

    private static bool DerivesFrom(ITypeSymbol type, string baseTypeFullName)
    {
        for (var current = type; current is not null; current = current.BaseType)
        {
            if (current.ToDisplayString() == baseTypeFullName)
                return true;
        }

        return false;
    }

    private static int? IntArgument(AttributeData attribute, int position, string name)
    {
        if (attribute.ConstructorArguments.Length > position && attribute.ConstructorArguments[position].Value is int value)
            return value;

        foreach (var argument in attribute.NamedArguments)
        {
            if (argument.Key == name && argument.Value.Value is int named)
                return named;
        }

        return null;
    }

    private static string? StringArgument(AttributeData attribute, int position, string name)
    {
        if (attribute.ConstructorArguments.Length > position && attribute.ConstructorArguments[position].Value is string value)
            return value;

        return NamedString(attribute, name);
    }

    private static bool? BoolArgument(AttributeData attribute, string name)
    {
        foreach (var argument in attribute.NamedArguments)
        {
            if (argument.Key == name && argument.Value.Value is bool value)
                return value;
        }

        return null;
    }

    /// <summary>Whether the property is <c>NextORM.Core.Range&lt;T&gt;</c> or a nullable of it.</summary>
    private static bool IsRangeType(ITypeSymbol type)
    {
        if (type is INamedTypeSymbol { OriginalDefinition.SpecialType: SpecialType.System_Nullable_T } nullable)
            type = nullable.TypeArguments[0];

        return type is INamedTypeSymbol named
            && named.Name == "Range"
            && named.Arity == 1
            && named.ContainingNamespace?.ToDisplayString() == CoreNamespace;
    }

    private static string? NamedString(AttributeData attribute, string name)
    {
        foreach (var argument in attribute.NamedArguments)
        {
            if (argument.Key == name && argument.Value.Value is string value)
                return value;
        }

        return null;
    }

    /// <summary>
    /// Whether the type and every type that contains it can be named from generated code in the same
    /// assembly: a private nested type (or a type inside one) is not reachable from another class.
    /// </summary>
    private static bool IsAccessibleInsideAssembly(INamedTypeSymbol symbol)
    {
        for (var type = symbol; type is not null; type = type.ContainingType)
        {
            if (type.DeclaredAccessibility is not (Accessibility.Public or Accessibility.Internal))
                return false;
            if (type.IsGenericType)
                return false;
        }

        return true;
    }

    private sealed record CoveredEntity(
        string FullName,
        string TableName,
        bool IsTableNameAuto,
        string? Schema,
        string TypeName,
        List<CoveredProperty> Properties,
        List<CoveredFilter> Filters);

    /// <summary>
    /// One <c>[QueryFilter]</c> declaration. <paramref name="MemberReference"/> is the generated
    /// expression naming the static member (or its invocation); <see langword="null"/> for a keyed
    /// declaration that only removes a filter slot.
    /// </summary>
    private sealed record CoveredFilter(string? Key, string? MemberReference, bool IsLambda);

    private sealed record CoveredProperty(
        string Name,
        string ColumnName,
        bool IsColumnNameAuto,
        bool IsKey,
        bool IsIdentity,
        bool IsComputed,
        int? DecimalPrecision,
        int? DecimalScale,
        string? Collation,
        int? DurationUnit,
        int DurationPrecision,
        RangeDescriptor? Range);

    private sealed record RangeDescriptor(
        string LowerColumn,
        string UpperColumn,
        bool LowerInclusive,
        bool UpperInclusive);
}
