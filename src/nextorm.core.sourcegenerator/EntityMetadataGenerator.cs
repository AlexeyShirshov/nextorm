using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace NextORM.Core.SourceGenerator;

/// <summary>
/// Emits a compile-time description of every entity mapping this project declares, so the runtime can
/// build the mapping without reflecting over the entity's members.
/// <para>
/// The description is the same data the reflective auto-build derives from attributes: the table name,
/// the mapped columns, keys and identity/computed flags. The generator is deliberately conservative —
/// a type that uses a construct it does not reproduce exactly (a relationship, a query filter, a value or
/// JSON converter, a range pair, a duration or decimal-precision mapping, inheritance, a generic or
/// nested-in-generic declaration) is simply not covered, and the runtime keeps the reflective path for
/// it. Coverage therefore grows by widening this description, never by guessing.
/// </para>
/// <para>
/// Run-time mappings are unaffected: a fluent <c>From&lt;T&gt;(cfg =&gt; ...)</c> mapping, an EF Core
/// model or a per-scope variant is published into the metadata cache first, and the generated
/// description is only consulted when no such entry exists.
/// </para>
/// </summary>
[Generator]
internal sealed class EntityMetadataGenerator : IIncrementalGenerator
{
    private const string GeneratedNamespace = "NextORM.Core.Generated";
    private const string ProviderName = "__NextOrmEntityMetadata";
    private const string CoreNamespace = "NextORM.Core";

    private const string SqlTableAttribute = CoreNamespace + ".SqlTableAttribute";
    private const string TableAttribute = "System.ComponentModel.DataAnnotations.Schema.TableAttribute";
    private const string ColumnAttribute = "System.ComponentModel.DataAnnotations.Schema.ColumnAttribute";
    private const string KeyAttribute = "System.ComponentModel.DataAnnotations.KeyAttribute";
    private const string DatabaseGeneratedAttribute = "System.ComponentModel.DataAnnotations.Schema.DatabaseGeneratedAttribute";
    private const string NotMappedAttribute = "System.ComponentModel.DataAnnotations.Schema.NotMappedAttribute";
    private const string TimestampAttribute = "System.ComponentModel.DataAnnotations.TimestampAttribute";
    private const string DecimalPrecisionAttribute = CoreNamespace + ".DecimalPrecisionAttribute";
    private const string CollationAttribute = CoreNamespace + ".CollationAttribute";
    private const string DurationAttribute = CoreNamespace + ".DurationAttribute";
    private const string RangeColumnsAttribute = CoreNamespace + ".RangeColumnsAttribute";
    private const string QueryFilterAttribute = CoreNamespace + ".QueryFilterAttribute";
    private const string RelationshipAttribute = CoreNamespace + ".RelationshipAttribute";
    private const string ValueConverterAttribute = CoreNamespace + ".ValueConverterAttribute";
    private const string JsonColumnAttribute = CoreNamespace + ".JsonColumnAttribute";
    private const string ConverterInterface = CoreNamespace + ".IPropertyValueConverter";
    private const string JsonSerializerContextType = "System.Text.Json.Serialization.JsonSerializerContext";
    private const string JsonSerializableAttribute = "System.Text.Json.Serialization.JsonSerializableAttribute";

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var declared = context.SyntaxProvider.CreateSyntaxProvider(
                static (node, _) => node is TypeDeclarationSyntax,
                static (ctx, _) => ctx.SemanticModel.GetDeclaredSymbol((TypeDeclarationSyntax)ctx.Node) as INamedTypeSymbol)
            .Where(static symbol => symbol is not null)
            .Select(static (symbol, _) => symbol!);

        context.RegisterSourceOutput(declared.Collect(), static (output, symbols) => Emit(output, symbols));
    }

    private static void Emit(SourceProductionContext context, ImmutableArray<INamedTypeSymbol> symbols)
    {
        var seen = new HashSet<INamedTypeSymbol>(SymbolEqualityComparer.Default);
        var jsonContexts = CollectJsonContexts(symbols);
        var covered = new List<CoveredEntity>();
        foreach (var symbol in symbols)
        {
            if (!seen.Add(symbol) || Describe(symbol, jsonContexts) is not { } entity)
                continue;
            covered.Add(entity);
        }

        if (covered.Count == 0)
            return;

        covered.Sort(static (left, right) => string.CompareOrdinal(left.FullName, right.FullName));

        var source = new StringBuilder();
        source.AppendLine("// <auto-generated/>");
        source.AppendLine("#nullable enable");
        source.AppendLine();
        source.Append("namespace ").Append(GeneratedNamespace).AppendLine(";");
        source.AppendLine();
        source.Append("internal static class ").AppendLine(ProviderName);
        source.AppendLine("{");

        // One annotated type handle per entity: the annotation is what lets the generated code resolve a
        // property by name without a trim warning, and it also tells the trimmer to keep the members. The
        // constructors are part of it because materializing the entity instantiates it.
        var handles = new Dictionary<string, string>(StringComparer.Ordinal);
        for (var i = 0; i < covered.Count; i++)
        {
            handles["global::" + covered[i].FullName] = "Entity" + i;
            source.Append("    [global::System.Diagnostics.CodeAnalysis.DynamicallyAccessedMembers(global::System.Diagnostics.CodeAnalysis.DynamicallyAccessedMemberTypes.PublicProperties | global::System.Diagnostics.CodeAnalysis.DynamicallyAccessedMemberTypes.PublicConstructors)]")
                .AppendLine();
            source.Append("    private static readonly global::System.Type Entity").Append(i)
                .Append(" = typeof(global::").Append(covered[i].FullName).AppendLine(");");
            source.AppendLine();
        }

        // A relationship names a related entity that is not necessarily an entity this generator covers
        // (a plain type the application never maps as a table), so those types get a handle of their own:
        // the key members are read from them and have to survive trimming.
        var relationIndex = 0;
        foreach (var relationship in covered.SelectMany(static entity => entity.Relationships))
        {
            foreach (var owner in new[] { relationship.RelatedType, relationship.ForeignKeyOwner, relationship.PrincipalKeyOwner })
            {
                if (owner is null || handles.ContainsKey(owner))
                    continue;

                var handle = "Relation" + relationIndex++;
                handles[owner] = handle;
                source.Append("    [global::System.Diagnostics.CodeAnalysis.DynamicallyAccessedMembers(global::System.Diagnostics.CodeAnalysis.DynamicallyAccessedMemberTypes.PublicProperties)]")
                    .AppendLine();
                source.Append("    private static readonly global::System.Type ").Append(handle)
                    .Append(" = typeof(").Append(owner).AppendLine(");");
                source.AppendLine();
            }
        }

        if (covered.Any(static entity => entity.Relationships.Count > 0))
        {
            // The navigation and key members are resolved by name, exactly as the reflective build resolves
            // them; the annotation on the handle is what makes that lookup trim-safe.
            source.AppendLine("    private static global::System.Reflection.PropertyInfo Member(");
            source.AppendLine("        [global::System.Diagnostics.CodeAnalysis.DynamicallyAccessedMembers(global::System.Diagnostics.CodeAnalysis.DynamicallyAccessedMemberTypes.PublicProperties)] global::System.Type owner,");
            source.AppendLine("        string name)");
            source.AppendLine("        => owner.GetProperty(name, global::System.Reflection.BindingFlags.Public | global::System.Reflection.BindingFlags.Instance | global::System.Reflection.BindingFlags.FlattenHierarchy)!;");
            source.AppendLine();
        }

        source.AppendLine("    [global::System.Runtime.CompilerServices.ModuleInitializer]");
        source.AppendLine("    internal static void Initialize()");
        source.AppendLine("    {");

        for (var i = 0; i < covered.Count; i++)
            EmitEntity(source, covered[i], i, handles);

        source.AppendLine("    }");
        source.AppendLine("}");
        context.AddSource("__NextOrmEntityMetadata.g.cs", source.ToString());
    }

    private static void EmitEntity(StringBuilder source, CoveredEntity entity, int index, Dictionary<string, string> handles)
    {
        source.Append("        global::NextORM.Core.GeneratedEntityMetadata.Register(typeof(global::")
            .Append(entity.FullName).Append("), static () =>").AppendLine();
        source.AppendLine("            new global::NextORM.Core.EntityMetadataDescriptor");
        source.AppendLine("            {");
        source.Append("                TableName = ").Append(Literal(entity.TableName)).AppendLine(",");
        if (entity.Schema is null)
            source.AppendLine("                Schema = null,");
        else
            source.Append("                Schema = ").Append(Literal(entity.Schema)).AppendLine(",");
        source.Append("                IsTableNameAuto = ").Append(Boolean(entity.IsTableNameAuto)).AppendLine(",");
        source.Append("                TypeName = ").Append(Literal(entity.TypeName)).AppendLine(",");
        source.AppendLine("                Properties = new global::NextORM.Core.EntityPropertyDescriptor[]");
        source.AppendLine("                {");
        foreach (var property in entity.Properties)
        {
            source.AppendLine("                    new global::NextORM.Core.EntityPropertyDescriptor");
            source.AppendLine("                    {");
            source.Append("                        Property = Entity").Append(index)
                .Append(".GetProperty(").Append(Literal(property.Name)).AppendLine(")!,");
            source.Append("                        ColumnName = ").Append(Literal(property.ColumnName)).AppendLine(",");
            source.Append("                        IsColumnNameAuto = ").Append(Boolean(property.IsColumnNameAuto)).AppendLine(",");
            if (property.IsKey)
                source.AppendLine("                        IsKey = true,");
            if (property.IsIdentity)
                source.AppendLine("                        IsIdentity = true,");
            if (property.IsComputed)
                source.AppendLine("                        IsComputed = true,");
            if (property.DecimalPrecision is { } precision)
                source.Append("                        DecimalPrecision = ").Append(precision).AppendLine(",");
            if (property.DecimalScale is { } scale)
                source.Append("                        DecimalScale = ").Append(scale).AppendLine(",");
            if (property.Collation is not null)
                source.Append("                        Collation = ").Append(Literal(property.Collation)).AppendLine(",");
            if (property.DurationUnit is { } durationUnit)
                source.Append("                        DurationUnit = (global::NextORM.Core.DurationUnit)").Append(durationUnit).AppendLine(",");
            if (property.DurationPrecision != 0)
                source.Append("                        DurationPrecision = ").Append(property.DurationPrecision).AppendLine(",");
            if (property.Converter is not null)
                source.Append("                        Converter = ").Append(property.Converter).AppendLine(",");
            if (property.Range is { } range)
            {
                source.Append("                        RangeColumns = new global::NextORM.Core.RangeColumnsMetadata(")
                    .Append(Literal(range.LowerColumn)).Append(", ")
                    .Append(Literal(range.UpperColumn)).Append(", ")
                    .Append(Boolean(range.LowerInclusive)).Append(", ")
                    .Append(Boolean(range.UpperInclusive)).AppendLine("),");
            }

            source.AppendLine("                    },");
        }

        source.AppendLine("                },");

        if (entity.Filters.Count > 0)
        {
            source.AppendLine("                Filters = new global::NextORM.Core.EntityFilterDescriptor[]");
            source.AppendLine("                {");
            foreach (var filter in entity.Filters)
            {
                source.AppendLine("                    new global::NextORM.Core.EntityFilterDescriptor");
                source.AppendLine("                    {");
                if (filter.Key is not null)
                    source.Append("                        Key = ").Append(Literal(filter.Key)).AppendLine(",");
                if (filter.MemberReference is not null)
                {
                    source.Append("                        ").Append(filter.IsLambda ? "Lambda" : "Func")
                        .Append(" = ").Append(filter.MemberReference).AppendLine(",");
                }

                source.AppendLine("                    },");
            }

            source.AppendLine("                },");
        }

        if (entity.Relationships.Count > 0)
        {
            source.AppendLine("                Relationships = new global::NextORM.Core.EntityRelationshipDescriptor[]");
            source.AppendLine("                {");
            foreach (var relationship in entity.Relationships)
            {
                source.AppendLine("                    new global::NextORM.Core.EntityRelationshipDescriptor");
                source.AppendLine("                    {");
                source.Append("                        DeclaringType = Entity").Append(index).AppendLine(",");
                source.Append("                        Navigation = Member(Entity").Append(index).Append(", ")
                    .Append(Literal(relationship.NavigationName)).AppendLine("),");
                source.Append("                        RelatedType = ").Append(handles[relationship.RelatedType]).AppendLine(",");
                if (relationship.IsCollection)
                    source.AppendLine("                        IsCollection = true,");
                source.Append("                        ForeignKeys = new global::System.Reflection.PropertyInfo[] { ")
                    .Append(string.Join(", ", relationship.ForeignKeyNames.Select(name => "Member(" + handles[relationship.ForeignKeyOwner] + ", " + Literal(name) + ")")))
                    .AppendLine(" },");
                if (relationship.PrincipalKeyOwner is { } principalOwner && relationship.PrincipalKeyNames is { } principalNames)
                {
                    source.Append("                        PrincipalKeys = new global::System.Reflection.PropertyInfo[] { ")
                        .Append(string.Join(", ", principalNames.Select(name => "Member(" + handles[principalOwner] + ", " + Literal(name) + ")")))
                        .AppendLine(" },");
                }

                source.AppendLine("                    },");
            }

            source.AppendLine("                },");
        }

        source.AppendLine("            }.Build());");
    }

    private static string Boolean(bool value) => value ? "true" : "false";

    /// <summary>Writes a C# string literal, escaping what a table or column name may contain.</summary>
    private static string Literal(string value)
    {
        var builder = new StringBuilder(value.Length + 2);
        builder.Append('"');
        foreach (var character in value)
        {
            switch (character)
            {
                case '"': builder.Append("\\\""); break;
                case '\\': builder.Append("\\\\"); break;
                case '\n': builder.Append("\\n"); break;
                case '\r': builder.Append("\\r"); break;
                case '\t': builder.Append("\\t"); break;
                default: builder.Append(character); break;
            }
        }

        builder.Append('"');
        return builder.ToString();
    }

    /// <summary>
    /// Maps a stored model type to the serializer options of the source-generated
    /// <c>JsonSerializerContext</c> that declares it. A model declared by two contexts is left out: which
    /// context's options apply is the application's choice, not something generated code should guess.
    /// </summary>
    private static Dictionary<INamedTypeSymbol, string> CollectJsonContexts(ImmutableArray<INamedTypeSymbol> symbols)
    {
        var contexts = new Dictionary<INamedTypeSymbol, string>(SymbolEqualityComparer.Default);
        var ambiguous = new HashSet<INamedTypeSymbol>(SymbolEqualityComparer.Default);

        foreach (var symbol in symbols)
        {
            if (symbol.TypeKind != TypeKind.Class || !DerivesFrom(symbol, JsonSerializerContextType))
                continue;
            // The generated class that references it lives in this assembly, so an inaccessible context
            // cannot be named from generated code.
            if (!IsAccessibleInsideAssembly(symbol))
                continue;

            var options = TypeReference(symbol) + ".Default.Options";
            foreach (var attribute in symbol.GetAttributes())
            {
                if (AttributeName(attribute) != JsonSerializableAttribute)
                    continue;
                if (attribute.ConstructorArguments.Length != 1 || attribute.ConstructorArguments[0].Value is not INamedTypeSymbol model)
                    continue;

                if (!contexts.ContainsKey(model))
                    contexts[model] = options;
                else
                    ambiguous.Add(model);
            }
        }

        foreach (var model in ambiguous)
            contexts.Remove(model);

        return contexts;
    }

    private static CoveredEntity? Describe(INamedTypeSymbol symbol, Dictionary<INamedTypeSymbol, string> jsonContexts)
    {
        if (symbol.TypeKind is not (TypeKind.Class or TypeKind.Interface))
            return null;
        // An interface is abstract by definition; only an abstract class is skipped.
        if (symbol.TypeKind == TypeKind.Class && symbol.IsAbstract)
            return null;
        if (symbol.IsStatic || symbol.IsGenericType)
            return null;
        if (!IsAccessibleInsideAssembly(symbol))
            return null;

        // Inheritance changes which properties are visible (FlattenHierarchy) and lets an attribute on a
        // base interface win, so the reflective result is not reproducible from this declaration alone.
        if (symbol.TypeKind == TypeKind.Class && symbol.BaseType is { SpecialType: not SpecialType.System_Object })
            return null;
        if (symbol.TypeKind == TypeKind.Interface && symbol.Interfaces.Length != 0)
            return null;

        var typeAttributes = symbol.GetAttributes();
        string? tableName = null;
        var tableNameAuto = true;
        var hasMappingAttribute = false;
        var filters = new List<CoveredFilter>();

        foreach (var attribute in typeAttributes)
        {
            var name = attribute.AttributeClass?.ToDisplayString() ?? string.Empty;
            if (name == SqlTableAttribute)
            {
                if (attribute.ConstructorArguments.Length != 1 || attribute.ConstructorArguments[0].Value is not string declared)
                    return null;
                tableName = declared;
                tableNameAuto = false;
                hasMappingAttribute = true;
            }
            else if (name == TableAttribute)
            {
                tableName = attribute.ConstructorArguments.Length == 1 && attribute.ConstructorArguments[0].Value is string declared
                    ? declared
                    : NamedString(attribute, "Name");
                if (tableName is null)
                    return null;
                tableNameAuto = false;
                hasMappingAttribute = true;
            }
            else if (name == QueryFilterAttribute)
            {
                if (DescribeFilter(symbol, attribute) is not { } filter)
                    return null;
                filters.Add(filter);
            }
            else if (IsUnreproducible(name))
            {
                return null;
            }
        }

        // The reflective table-name resolution reads the implemented interfaces after the entity's own
        // attributes and lets an interface declaration win, so the generated name has to follow it. Which
        // interface wins is the reflection order, so two candidates are not reproducible and the type keeps
        // the reflective path.
        if (symbol.TypeKind == TypeKind.Class)
        {
            string? interfaceTableName = null;
            var interfaceCandidates = 0;
            foreach (var implemented in symbol.AllInterfaces)
            {
                foreach (var attribute in implemented.GetAttributes())
                {
                    var name = AttributeName(attribute);
                    if (name is not (SqlTableAttribute or TableAttribute))
                        continue;
                    if (DeclaredTableName(name, attribute) is not { } declared)
                        return null;
                    interfaceCandidates++;
                    interfaceTableName = declared;
                }
            }

            if (interfaceCandidates > 1)
                return null;
            if (interfaceTableName is not null)
            {
                tableName = interfaceTableName;
                tableNameAuto = false;
                hasMappingAttribute = true;
            }
        }

        // A class property may carry no mapping attribute because the mapping is declared on the interface
        // it implements: the reflective build falls back to the interface property, attribute by attribute.
        // Two interfaces declaring the same property make the winner order-dependent, so a type in that
        // shape is not covered.
        var interfaceProperties = new Dictionary<string, IPropertySymbol?>(StringComparer.Ordinal);
        if (symbol.TypeKind == TypeKind.Class)
        {
            foreach (var implemented in symbol.AllInterfaces)
            {
                foreach (var member in implemented.GetMembers())
                {
                    if (member is not IPropertySymbol interfaceProperty || interfaceProperty.IsStatic || interfaceProperty.IsIndexer)
                        continue;
                    interfaceProperties[interfaceProperty.Name] =
                        interfaceProperties.ContainsKey(interfaceProperty.Name) ? null : interfaceProperty;
                }
            }
        }

        var properties = new List<CoveredProperty>();
        var relationships = new List<CoveredRelationship>();
        foreach (var member in symbol.GetMembers())
        {
            if (member is not IPropertySymbol property)
                continue;
            if (property.IsStatic || property.IsIndexer)
                continue;
            if (property.DeclaredAccessibility != Accessibility.Public)
                continue;

            var attributes = MergeAttributes(property.GetAttributes(), interfaceProperties, property);
            if (attributes is null)
                return null;

            // A navigation is never a column - the reflective build excludes it from the column map before
            // it reads any other attribute, and so does this description. Only the property's own
            // declaration counts: unlike the column attributes, the reflective relationship scan has no
            // interface fallback.
            if (property.GetAttributes().FirstOrDefault(attribute => AttributeName(attribute) == RelationshipAttribute) is { } relationshipAttribute)
            {
                if (DescribeRelationship(symbol, property, relationshipAttribute) is not { } relationship)
                    return null;
                relationships.Add(relationship);
                continue;
            }

            // GetProperties(Public | Instance) returns only writable properties, so a get-only property is
            // not a column - but the attributes on it still shape the mapping.
            if (property.SetMethod is null)
            {
                if (attributes.Any(attribute => IsUnreproducible(AttributeName(attribute))))
                    return null;
                continue;
            }

            if (ReadPropertyAttributes(property.Type, attributes, jsonContexts) is not { } declared)
                return null;

            if (declared.Range is not null && !IsRangeType(property.Type))
                return null;

            var columnName = declared.Range?.LowerColumn
                ?? (string.IsNullOrEmpty(declared.DeclaredColumn) ? null : declared.DeclaredColumn);

            if (columnName is not null || declared.IsKey)
                hasMappingAttribute = true;

            properties.Add(new CoveredProperty(
                Name: property.Name,
                ColumnName: columnName ?? property.Name,
                IsColumnNameAuto: columnName is null,
                IsKey: declared.IsKey,
                IsIdentity: declared.IsIdentity,
                IsComputed: declared.IsComputed,
                DecimalPrecision: declared.DecimalPrecision,
                DecimalScale: declared.DecimalScale,
                Collation: declared.Collation,
                DurationUnit: declared.DurationUnit,
                DurationPrecision: declared.DurationPrecision,
                Range: declared.Range,
                Converter: declared.Converter));
        }

        // A type with no mapping attribute at all is not necessarily an entity (the auto table name makes
        // every settable class an entity, which would describe plain DTOs and value objects), so it keeps
        // the reflective path until it declares its mapping.
        if (!hasMappingAttribute || properties.Count == 0)
            return null;

        var fullName = symbol.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat).Replace("global::", string.Empty);
        return new CoveredEntity(fullName, tableName ?? symbol.Name, tableNameAuto, Schema: null, symbol.Name, properties, filters, relationships);
    }

    /// <summary>
    /// Combines the attributes a class property declares with the ones declared on the matching interface
    /// property, the way the reflective build falls back per attribute. Returns <see langword="null"/>
    /// when more than one interface declares the property.
    /// </summary>
    private static List<AttributeData>? MergeAttributes(
        ImmutableArray<AttributeData> own,
        Dictionary<string, IPropertySymbol?> interfaceProperties,
        IPropertySymbol property)
    {
        var merged = new List<AttributeData>(own.Length);
        merged.AddRange(own);

        if (!interfaceProperties.TryGetValue(property.Name, out var interfaceProperty))
            return merged;
        // More than one interface declares the property: which one the reflective fallback reads is the
        // interface order, so the type keeps the reflective path.
        if (interfaceProperty is null)
            return null;
        // An interface member of another type is not the member this property implements, so the
        // reflective fallback does not read it either.
        if (!SymbolEqualityComparer.Default.Equals(interfaceProperty.Type, property.Type))
            return merged;

        var declared = new HashSet<string>(own.Select(AttributeName), StringComparer.Ordinal);
        foreach (var attribute in interfaceProperty.GetAttributes())
        {
            if (declared.Add(AttributeName(attribute)))
                merged.Add(attribute);
        }

        return merged;
    }

    private static string AttributeName(AttributeData attribute)
        => attribute.AttributeClass?.ToDisplayString() ?? string.Empty;

    /// <summary>
    /// Reads the table name a <see cref="SqlTableAttribute"/> or <c>TableAttribute</c> declares, or returns
    /// <see langword="null"/> when the declaration cannot be read without invoking it.
    /// </summary>
    private static string? DeclaredTableName(string attributeName, AttributeData attribute)
    {
        if (attributeName == SqlTableAttribute)
            return attribute.ConstructorArguments.Length == 1 && attribute.ConstructorArguments[0].Value is string declared
                ? declared
                : null;

        return attribute.ConstructorArguments.Length == 1 && attribute.ConstructorArguments[0].Value is string declaredName
            ? declaredName
            : NamedString(attribute, "Name");
    }

    /// <summary>
    /// Reads the mapping attributes of one property, or returns <see langword="null"/> when one of them
    /// changes the metadata in a way this generator does not reproduce exactly (the type then keeps the
    /// reflective path).
    /// </summary>
    private static PropertyMapping? ReadPropertyAttributes(
        ITypeSymbol propertyType,
        List<AttributeData> attributes,
        Dictionary<INamedTypeSymbol, string> jsonContexts)
    {
        string? declaredColumn = null;
        var isKey = false;
        var isIdentity = false;
        var isComputed = false;
        int? decimalPrecision = null;
        int? decimalScale = null;
        string? collation = null;
        int? durationUnit = null;
        var durationPrecision = 0;
        RangeDescriptor? range = null;
        string? converter = null;
        var hasValueConverter = false;
        var hasJsonColumn = false;

        foreach (var attribute in attributes)
        {
            var name = AttributeName(attribute);
            if (name == ColumnAttribute)
            {
                declaredColumn = attribute.ConstructorArguments.Length == 1
                    ? attribute.ConstructorArguments[0].Value as string
                    : NamedString(attribute, "Name");
            }
            else if (name == KeyAttribute)
            {
                isKey = true;
            }
            else if (name == DatabaseGeneratedAttribute)
            {
                // DatabaseGeneratedOption: None = 0, Identity = 1, Computed = 2.
                var option = attribute.ConstructorArguments.Length == 1 && attribute.ConstructorArguments[0].Value is int value
                    ? value
                    : 0;
                isIdentity = option == 1;
                isComputed = option == 2;
            }
            else if (name == DecimalPrecisionAttribute)
            {
                decimalPrecision = IntArgument(attribute, 0, "Precision");
                decimalScale = IntArgument(attribute, 1, "Scale");
            }
            else if (name == CollationAttribute)
            {
                collation = StringArgument(attribute, 0, "Name");
                if (string.IsNullOrEmpty(collation))
                    return null;
            }
            else if (name == DurationAttribute)
            {
                // The parameterless constructor means ticks, the CLR storage unit.
                durationUnit = IntArgument(attribute, 0, "Unit") ?? 0;
                durationPrecision = IntArgument(attribute, 1, "Precision") ?? 0;
            }
            else if (name == RangeColumnsAttribute)
            {
                var lower = StringArgument(attribute, 0, "LowerColumn");
                var upper = StringArgument(attribute, 1, "UpperColumn");
                if (string.IsNullOrEmpty(lower) || string.IsNullOrEmpty(upper))
                    return null;
                range = new RangeDescriptor(
                    lower!,
                    upper!,
                    BoolArgument(attribute, "LowerInclusive") ?? true,
                    BoolArgument(attribute, "UpperInclusive") ?? false);
            }
            else if (name == ValueConverterAttribute)
            {
                if (DescribeValueConverter(attribute, propertyType) is not { } expression)
                    return null;
                converter = expression;
                hasValueConverter = true;
            }
            else if (name == JsonColumnAttribute)
            {
                if (DescribeJsonColumn(attribute, propertyType, jsonContexts) is not { } expression)
                    return null;
                converter = expression;
                hasJsonColumn = true;
            }
            else if (name is NotMappedAttribute or TimestampAttribute || IsUnreproducible(name))
            {
                return null;
            }
        }

        // The reflective build refuses these combinations at run time; a generated mapping would have to
        // pick one of them, so the type keeps the path that reports the failure.
        if (hasValueConverter && hasJsonColumn)
            return null;
        if (range is not null && (converter is not null || declaredColumn is not null))
            return null;

        return new PropertyMapping(
            declaredColumn,
            isKey,
            isIdentity,
            isComputed,
            decimalPrecision,
            decimalScale,
            collation,
            durationUnit,
            durationPrecision,
            range,
            converter);
    }

    /// <summary>
    /// Names the converter expression of a <c>[ValueConverter]</c> declaration: a direct <c>new</c> of the
    /// converter type, so the mapping needs no <c>Activator.CreateInstance</c>. Returns
    /// <see langword="null"/> for a converter whose construction or model-type check cannot be settled at
    /// compile time.
    /// </summary>
    private static string? DescribeValueConverter(AttributeData attribute, ITypeSymbol propertyType)
    {
        if (attribute.ConstructorArguments.Length != 1 || attribute.ConstructorArguments[0].Value is not INamedTypeSymbol converterType)
            return null;

        // Mirrors the run-time rules: a closed, non-abstract class with a public parameterless
        // constructor that implements IPropertyValueConverter, whose typed model matches the property.
        if (converterType.TypeKind != TypeKind.Class || converterType.IsAbstract)
            return null;
        if (converterType.IsUnboundGenericType || ContainsTypeParameter(converterType))
            return null;
        if (converterType.DeclaredAccessibility != Accessibility.Public)
            return null;
        if (!converterType.AllInterfaces.Any(implemented => implemented.ToDisplayString() == ConverterInterface))
            return null;
        if (!converterType.InstanceConstructors.Any(static constructor =>
                constructor.Parameters.Length == 0 && constructor.DeclaredAccessibility == Accessibility.Public))
            return null;

        var modelType = ConverterModelType(converterType);
        if (modelType is not null
            && !SymbolEqualityComparer.Default.Equals(modelType, propertyType)
            && !SymbolEqualityComparer.Default.Equals(modelType, NullableUnderlying(propertyType)))
            return null;

        return "new " + TypeReference(converterType) + "()";
    }

    /// <summary>
    /// Names the converter expression of a <c>[JsonColumn]</c> declaration. The closed generic call is
    /// instantiated by the compiler, so the mapping replaces the run-time
    /// <c>MakeGenericType</c> + <c>Activator</c> the reflective build needs.
    /// </summary>
    private static string? DescribeJsonColumn(
        AttributeData attribute,
        ITypeSymbol propertyType,
        Dictionary<INamedTypeSymbol, string> jsonContexts)
    {
        // JsonColumnStorage: Auto = 0, Native = 1, Text = 2.
        var storage = IntArgument(attribute, 0, "Storage") ?? 0;
        if (storage is < 0 or > 2 || ContainsTypeParameter(propertyType))
            return null;

        // The stored model may be declared by the application's source-generated JsonSerializerContext; its
        // options are what a trimmed application needs, because the default options resolve contract
        // metadata reflectively. Without one the column keeps the serializer defaults, which is enough on
        // the JIT runtime.
        var options = propertyType is INamedTypeSymbol model && jsonContexts.TryGetValue(model, out var declared)
            ? ", " + declared
            : string.Empty;

        return "global::NextORM.Core.JsonColumnConverters.Create<" + TypeReference(propertyType)
            + ">((global::NextORM.Core.JsonColumnStorage)" + storage + options + ")";
    }

    /// <summary>The model type of a <c>ValueConverter&lt;TModel, TProvider&gt;</c> subclass, or null for a plain implementation.</summary>
    private static ITypeSymbol? ConverterModelType(INamedTypeSymbol converterType)
    {
        for (var type = converterType.BaseType; type is not null; type = type.BaseType)
        {
            if (type is { Arity: 2, Name: "ValueConverter" } && type.ContainingNamespace?.ToDisplayString() == CoreNamespace)
                return type.TypeArguments[0];
        }

        return null;
    }

    private static ITypeSymbol? NullableUnderlying(ITypeSymbol type)
        => type is INamedTypeSymbol { OriginalDefinition.SpecialType: SpecialType.System_Nullable_T } nullable
            ? nullable.TypeArguments[0]
            : null;

    private static bool ContainsTypeParameter(ITypeSymbol type)
    {
        if (type is ITypeParameterSymbol or IErrorTypeSymbol)
            return true;
        if (type is IArrayTypeSymbol array)
            return ContainsTypeParameter(array.ElementType);
        if (type is INamedTypeSymbol named)
        {
            foreach (var argument in named.TypeArguments)
            {
                if (ContainsTypeParameter(argument))
                    return true;
            }
        }

        return false;
    }

    private static string TypeReference(ITypeSymbol type)
        => type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);

    /// <summary>
    /// Describes one <c>[Relationship]</c> declaration, or returns <see langword="null"/> when the
    /// declaration is one the reflective build refuses or resolves in a way this generator does not
    /// reproduce. A refusal must stay a refusal: a generated mapping that accepted the declaration would
    /// turn a deterministic exception into a working query.
    /// </summary>
    private static CoveredRelationship? DescribeRelationship(
        INamedTypeSymbol declaringType,
        IPropertySymbol navigation,
        AttributeData attribute)
    {
        var foreignKey = NamedString(attribute, "ForeignKey");
        var foreignKeys = StringArray(attribute, "ForeignKeys");
        var principalKeys = StringArray(attribute, "PrincipalKeys");

        // Exactly one of the two foreign-key forms, and no empty key array (an empty array is a refusal,
        // an omitted one means the default key).
        if (!string.IsNullOrWhiteSpace(foreignKey) == (foreignKeys is not null))
            return null;
        if (foreignKeys is { Length: 0 } || principalKeys is { Length: 0 })
            return null;

        var classification = ClassifyNavigation(navigation.Type, out var elementType);
        if (classification == NavigationShape.Ambiguous)
            return null;

        var isCollection = classification == NavigationShape.Collection;
        var relatedType = isCollection ? elementType : navigation.Type;
        // A reference navigation must be a class: the reflective build refuses a string or a value type,
        // and a collection of a value type has no members to key on.
        if (!isCollection && (relatedType.SpecialType == SpecialType.System_String || relatedType.IsValueType))
            return null;
        if (relatedType is not INamedTypeSymbol relatedNamed || !IsAccessibleInsideAssembly(relatedNamed))
            return null;

        var foreignKeyOwner = isCollection ? relatedType : declaringType;
        var principalKeyOwner = isCollection ? declaringType : relatedType;

        if (ResolveMemberNames(foreignKeyOwner, foreignKeys ?? new[] { foreignKey! }) is not { } resolvedForeignKeys)
            return null;

        IReadOnlyList<string>? resolvedPrincipalKeys = null;
        if (principalKeys is not null)
        {
            if (ResolveMemberNames(principalKeyOwner, principalKeys) is not { } principal)
                return null;
            if (principal.Count != resolvedForeignKeys.Count)
                return null;
            resolvedPrincipalKeys = principal;
        }

        return new CoveredRelationship(
            NavigationName: navigation.Name,
            IsCollection: isCollection,
            RelatedType: FullyQualified(relatedNamed),
            ForeignKeyOwner: FullyQualified(foreignKeyOwner),
            ForeignKeyNames: resolvedForeignKeys,
            PrincipalKeyOwner: resolvedPrincipalKeys is null ? null : FullyQualified(principalKeyOwner),
            PrincipalKeyNames: resolvedPrincipalKeys);
    }

    private enum NavigationShape
    {
        NotCollection,
        Collection,
        Ambiguous,
    }

    /// <summary>
    /// Classifies a navigation type the way the reflective <c>TryGetCollectionElementType</c> does: a
    /// non-string type that implements <c>IEnumerable&lt;T&gt;</c> is a collection of <c>T</c>. Several
    /// different element types leave the winner to the reflection order, so that shape is ambiguous.
    /// </summary>
    private static NavigationShape ClassifyNavigation(ITypeSymbol type, out ITypeSymbol elementType)
    {
        elementType = null!;
        if (type.SpecialType == SpecialType.System_String)
            return NavigationShape.NotCollection;

        if (type is IArrayTypeSymbol array)
        {
            elementType = array.ElementType;
            return NavigationShape.Collection;
        }

        var candidates = new List<ITypeSymbol>();
        if (EnumerableElement(type) is { } direct)
            candidates.Add(direct);
        if (type is INamedTypeSymbol named)
        {
            foreach (var implemented in named.AllInterfaces)
            {
                if (EnumerableElement(implemented) is { } element && !candidates.Any(existing => SymbolEqualityComparer.Default.Equals(existing, element)))
                    candidates.Add(element);
            }
        }

        if (candidates.Count == 0)
            return NavigationShape.NotCollection;
        if (candidates.Count > 1)
            return NavigationShape.Ambiguous;

        elementType = candidates[0];
        return NavigationShape.Collection;
    }

    private static ITypeSymbol? EnumerableElement(ITypeSymbol type)
        => type is INamedTypeSymbol { Name: "IEnumerable", Arity: 1 } enumerable
            && enumerable.ContainingNamespace?.ToDisplayString() == "System.Collections.Generic"
            ? enumerable.TypeArguments[0]
            : null;

    /// <summary>
    /// Resolves the declared key members on their owner type, or returns <see langword="null"/> when a
    /// name is empty, repeats, or names no public instance property (which the reflective build refuses).
    /// </summary>
    private static IReadOnlyList<string>? ResolveMemberNames(ITypeSymbol owner, IReadOnlyList<string> names)
    {
        var resolved = new List<string>(names.Count);
        var seen = new HashSet<string>(StringComparer.Ordinal);
        foreach (var name in names)
        {
            if (string.IsNullOrWhiteSpace(name) || !seen.Add(name))
                return null;
            if (FindPublicInstanceProperty(owner, name) is null)
                return null;
            resolved.Add(name);
        }

        return resolved;
    }

    /// <summary>
    /// The public instance property a name refers to, searched down the base-type chain the way
    /// <c>Type.GetProperty(..., FlattenHierarchy)</c> does. Inherited interface members are not searched:
    /// not finding the member only means the type keeps the reflective path.
    /// </summary>
    private static IPropertySymbol? FindPublicInstanceProperty(ITypeSymbol type, string name)
    {
        for (var current = type; current is not null && current.SpecialType != SpecialType.System_Object; current = current.BaseType)
        {
            foreach (var member in current.GetMembers(name))
            {
                if (member is IPropertySymbol property
                    && !property.IsStatic
                    && !property.IsIndexer
                    && property.DeclaredAccessibility == Accessibility.Public)
                    return property;
            }
        }

        return null;
    }

    private static string[]? StringArray(AttributeData attribute, string name)
    {
        foreach (var argument in attribute.NamedArguments)
        {
            if (argument.Key != name || argument.Value.IsNull)
                continue;
            if (argument.Value.Kind != TypedConstantKind.Array)
                return null;

            var values = argument.Value.Values;
            var result = new string[values.Length];
            for (var i = 0; i < values.Length; i++)
            {
                if (values[i].Value is not string value)
                    return null;
                result[i] = value;
            }

            return result;
        }

        return null;
    }

    private static string FullyQualified(ITypeSymbol type)
        => type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);

    /// <summary>
    /// Whether an attribute makes the mapping unreproducible. Every <c>NextORM.Core</c> mapping attribute
    /// other than <see cref="SqlTableAttribute"/> is excluded: relationships, query filters, value and JSON
    /// converters, range pairs, durations, collations, decimal precision, dynamic-columns stores and shard
    /// keys all change the resulting metadata in ways this generator does not model yet.
    /// </summary>
    private static bool IsUnreproducible(string attributeFullName)
    {
        if (attributeFullName is SqlTableAttribute or DecimalPrecisionAttribute or CollationAttribute
            or DurationAttribute or RangeColumnsAttribute or QueryFilterAttribute or ValueConverterAttribute
            or JsonColumnAttribute)
            return false;

        var namespaceEnd = attributeFullName.LastIndexOf('.');
        return namespaceEnd > 0 && attributeFullName.Substring(0, namespaceEnd) == CoreNamespace;
    }

    /// <summary>
    /// Reads one <c>[QueryFilter]</c> declaration, or returns <see langword="null"/> when it cannot be
    /// reproduced: both forms declared (the reflective build throws), a member that is not accessible to
    /// generated code, or a member whose type is not a predicate/function.
    /// </summary>
    private static CoveredFilter? DescribeFilter(INamedTypeSymbol entity, AttributeData attribute)
    {
        var key = NamedString(attribute, "FilterKey");
        var lambdaName = NamedString(attribute, "FilterLambda");
        var funcName = NamedString(attribute, "FilterFunc");

        var hasLambda = !string.IsNullOrWhiteSpace(lambdaName);
        var hasFunc = !string.IsNullOrWhiteSpace(funcName);
        if (hasLambda && hasFunc)
            return null;

        if (!hasLambda && !hasFunc)
            return string.IsNullOrWhiteSpace(key) ? null : new CoveredFilter(key, MemberReference: null, IsLambda: false);

        var member = ResolveStaticMember(entity, hasLambda ? lambdaName! : funcName!, expectLambda: hasLambda);
        return member is null ? null : new CoveredFilter(key, member, hasLambda);
    }

    /// <summary>
    /// Names a static field, property or parameterless method of the entity so generated code reads it
    /// directly, replacing the reflective <c>GetMember</c> + <c>GetValue</c>/<c>Invoke</c> lookup.
    /// </summary>
    private static string? ResolveStaticMember(INamedTypeSymbol entity, string name, bool expectLambda)
    {
        var typeReference = "global::" + entity.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat).Replace("global::", string.Empty);

        foreach (var member in entity.GetMembers(name))
        {
            switch (member)
            {
                case IPropertySymbol property when property.IsStatic && IsAccessibleToGeneratedCode(property.DeclaredAccessibility):
                    return DerivesFrom(property.Type, expectLambda ? "System.Linq.Expressions.LambdaExpression" : "System.Delegate")
                        ? typeReference + "." + property.Name
                        : null;
                case IFieldSymbol field when field.IsStatic && IsAccessibleToGeneratedCode(field.DeclaredAccessibility):
                    return DerivesFrom(field.Type, expectLambda ? "System.Linq.Expressions.LambdaExpression" : "System.Delegate")
                        ? typeReference + "." + field.Name
                        : null;
                case IMethodSymbol method when method.IsStatic && method.Parameters.Length == 0 && !method.IsGenericMethod
                    && IsAccessibleToGeneratedCode(method.DeclaredAccessibility):
                    return DerivesFrom(method.ReturnType, expectLambda ? "System.Linq.Expressions.LambdaExpression" : "System.Delegate")
                        ? typeReference + "." + method.Name + "()"
                        : null;
            }
        }

        return null;
    }

    // A private member is not reachable from the generated class, so the type keeps the reflective path.
    private static bool IsAccessibleToGeneratedCode(Accessibility accessibility)
        => accessibility is Accessibility.Public or Accessibility.Internal or Accessibility.ProtectedOrInternal;

    private static bool DerivesFrom(ITypeSymbol type, string baseTypeFullName)
    {
        for (var current = type; current is not null; current = current.BaseType)
        {
            if (current.ToDisplayString() == baseTypeFullName)
                return true;
        }

        return false;
    }

    private static int? IntArgument(AttributeData attribute, int position, string name)
    {
        if (attribute.ConstructorArguments.Length > position && attribute.ConstructorArguments[position].Value is int value)
            return value;

        foreach (var argument in attribute.NamedArguments)
        {
            if (argument.Key == name && argument.Value.Value is int named)
                return named;
        }

        return null;
    }

    private static string? StringArgument(AttributeData attribute, int position, string name)
    {
        if (attribute.ConstructorArguments.Length > position && attribute.ConstructorArguments[position].Value is string value)
            return value;

        return NamedString(attribute, name);
    }

    private static bool? BoolArgument(AttributeData attribute, string name)
    {
        foreach (var argument in attribute.NamedArguments)
        {
            if (argument.Key == name && argument.Value.Value is bool value)
                return value;
        }

        return null;
    }

    /// <summary>Whether the property is <c>NextORM.Core.Range&lt;T&gt;</c> or a nullable of it.</summary>
    private static bool IsRangeType(ITypeSymbol type)
    {
        if (type is INamedTypeSymbol { OriginalDefinition.SpecialType: SpecialType.System_Nullable_T } nullable)
            type = nullable.TypeArguments[0];

        return type is INamedTypeSymbol named
            && named.Name == "Range"
            && named.Arity == 1
            && named.ContainingNamespace?.ToDisplayString() == CoreNamespace;
    }

    private static string? NamedString(AttributeData attribute, string name)
    {
        foreach (var argument in attribute.NamedArguments)
        {
            if (argument.Key == name && argument.Value.Value is string value)
                return value;
        }

        return null;
    }

    /// <summary>
    /// Whether the type and every type that contains it can be named from generated code in the same
    /// assembly: a private nested type (or a type inside one) is not reachable from another class.
    /// </summary>
    private static bool IsAccessibleInsideAssembly(INamedTypeSymbol symbol)
    {
        for (var type = symbol; type is not null; type = type.ContainingType)
        {
            if (type.DeclaredAccessibility is not (Accessibility.Public or Accessibility.Internal))
                return false;
            if (type.IsGenericType)
                return false;
        }

        return true;
    }

